static const unsigned char *pd_font_glyph(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    for (unsigned i = 0; i < sizeof kGlyphs / sizeof kGlyphs[0]; i++)
        if (kGlyphs[i].c == c) return kGlyphs[i].col;
    return 0;
}

